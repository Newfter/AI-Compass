// The Pro design's keyboard jumps, in the keyboard shortcuts window (press ?).
// js/pro.js, 7: "g" then a letter; "`" goes to the terminal. Pro design only.
(function () {
    var data = window.AICompass.content.get("settings");
    if (!data || !Array.isArray(data.shortcuts)) return;
    data.shortcuts.push({
        title: "pro.keysGroup",
        items: [
            { keys: [["G", "H"]], sequence: true, does: "pro.do.jumpHome" },
            { keys: [["G", "P"]], sequence: true, does: "pro.do.jumpPath" },
            { keys: [["G", "L"]], sequence: true, does: "pro.do.jumpLessons" },
            { keys: [["G", "A"]], sequence: true, does: "pro.do.jumpLab" },
            { keys: [["G", "R"]], sequence: true, does: "pro.do.jumpResearch" },
            { keys: [["G", "Q"]], sequence: true, does: "pro.do.jumpQuiz" },
            { keys: [["G", "G"]], sequence: true, does: "pro.do.jumpGlossary" },
            { keys: [["G", "T"]], sequence: true, does: "pro.do.jumpHistory" },
            { keys: [["`"]], does: "pro.do.terminal" }
        ]
    });
})();
